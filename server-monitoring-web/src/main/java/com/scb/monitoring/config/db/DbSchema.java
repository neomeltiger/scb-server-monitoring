package com.scb.monitoring.config.db;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Map;

import javax.sql.DataSource;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.core.io.ClassPathResource;
import org.springframework.core.io.support.EncodedResource;
import org.springframework.jdbc.datasource.init.ScriptUtils;
import org.springframework.util.StreamUtils;

/**
 * 주 DB 로 바꿀 때 테이블 준비 : 테이블(tb_server)이 없는 빈 DB 면 스키마 + 기본 데이터(data.sql) + 사용자(users.sql) 생성,
 * 있으면 빠진 컬럼·테이블만 보완 ({@link SchemaUpgrade}).
 * <ul>
 *   <li>H2 : schema-ansi.sql / MySQL · MariaDB : schema-mysql.sql</li>
 *   <li>Oracle · Sybase : schema-ansi.sql 을 {@link DbDialect#ddl} 로 바꿔 실행</li>
 * </ul>
 */
public final class DbSchema {

    private static final Logger log = LoggerFactory.getLogger(DbSchema.class);

    public static final String ANSI = "db/schema-ansi.sql";

    private DbSchema() {
    }

    public static void ensure(DataSource ds, DbKind kind) {
        try (Connection c = ds.getConnection()) {
            if (!tableExists(c, kind, "tb_server")) create(c, kind);
        } catch (SQLException e) {
            throw new IllegalStateException(kind.label() + " 스키마 준비 실패 : " + NamedJdbc.rootMessage(e), e);
        }
        SchemaUpgrade.apply(ds, kind);
    }

    private static void create(Connection c, DbKind kind) throws SQLException {
        log.warn("DB : {} 에 테이블이 없어 새로 만듭니다 (스키마 + 기본 데이터 + 사용자)", kind.label());
        if (kind == DbKind.H2 || kind.mysqlFamily()) {
            String schema = kind == DbKind.H2 ? ANSI : "db/schema-mysql.sql";
            for (String script : new String[] {schema, "db/data.sql", "db/users.sql"}) {
                ScriptUtils.executeSqlScript(c, new EncodedResource(new ClassPathResource(script), StandardCharsets.UTF_8));
            }
            return;
        }
        String ansi = resource(ANSI);
        Map<String, String> ids = DbDialect.identityColumns(ansi);
        List<String> all = new ArrayList<>(DbDialect.ddl(ansi, kind));
        all.addAll(DbDialect.data(resource("db/data.sql"), kind, ids));
        all.addAll(DbDialect.data(resource("db/users.sql"), kind, ids));
        boolean auto = c.getAutoCommit();
        c.setAutoCommit(true);
        try (Statement st = c.createStatement()) {
            for (String sql : all) {
                try {
                    st.execute(sql);
                } catch (SQLException e) {
                    throw new SQLException(e.getMessage() + " - SQL : " + abbreviate(sql), e.getSQLState(), e.getErrorCode(), e);
                }
            }
        } finally {
            c.setAutoCommit(auto);
        }
        if (kind == DbKind.ORACLE) restartOracleIdentities(c, ids);
        log.info("DB : {} 스키마 생성 완료 ({} 문장)", kind.label(), all.size());
    }

    /** Oracle : 값을 직접 넣은 IDENTITY 컬럼의 다음 값을 최댓값 다음으로 */
    public static void restartOracleIdentities(Connection c, Map<String, String> ids) throws SQLException {
        try (Statement st = c.createStatement()) {
            for (Map.Entry<String, String> e : ids.entrySet()) {
                st.execute("ALTER TABLE " + e.getKey() + " MODIFY " + e.getValue() + " GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE)");
            }
        }
    }

    // ---------------------------------------------------------------- 메타데이터

    /** 테이블을 찾을 스키마 : Oracle = 접속 사용자, H2 = PUBLIC, 그 밖 = 현재 DB (null) */
    public static String schemaOf(Connection c, DbKind kind) throws SQLException {
        if (kind == DbKind.ORACLE) return c.getMetaData().getUserName().toUpperCase(Locale.ROOT);
        if (kind == DbKind.H2) return "PUBLIC";
        return null;
    }

    public static boolean tableExists(Connection c, DbKind kind, String table) throws SQLException {
        DatabaseMetaData md = c.getMetaData();
        String schema = schemaOf(c, kind);
        for (String t : new String[] {table, table.toUpperCase(Locale.ROOT)}) {
            try (ResultSet rs = md.getTables(c.getCatalog(), schema, t, new String[] {"TABLE"})) {
                if (rs.next()) return true;
            }
        }
        return false;
    }

    public static boolean columnExists(Connection c, DbKind kind, String table, String column) throws SQLException {
        DatabaseMetaData md = c.getMetaData();
        String schema = schemaOf(c, kind);
        for (String t : new String[] {table, table.toUpperCase(Locale.ROOT)}) {
            for (String col : new String[] {column, column.toUpperCase(Locale.ROOT)}) {
                try (ResultSet rs = md.getColumns(c.getCatalog(), schema, t, col)) {
                    if (rs.next()) return true;
                }
            }
        }
        return false;
    }

    /** 연결의 DB 제품 이름 → 종류 (모르면 H2 처럼 다룸) */
    public static DbKind kindOf(Connection c) throws SQLException {
        String p = c.getMetaData().getDatabaseProductName().toLowerCase(Locale.ROOT);
        if (p.contains("oracle")) return DbKind.ORACLE;
        if (p.contains("adaptive") || p.contains("sybase") || p.contains("sql server")) return DbKind.SYBASE;
        if (p.contains("mariadb")) return DbKind.MARIADB;
        if (p.contains("mysql")) return DbKind.MYSQL;
        return DbKind.H2;
    }

    public static String resource(String path) {
        try (InputStream in = new ClassPathResource(path).getInputStream()) {
            return StreamUtils.copyToString(in, StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new IllegalStateException("리소스 읽기 실패 : " + path, e);
        }
    }

    private static String abbreviate(String sql) {
        String s = sql.replaceAll("\\s+", " ");
        return s.length() > 160 ? s.substring(0, 160) + "..." : s;
    }
}
