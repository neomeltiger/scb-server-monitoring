CREATE TABLE tb_net_node (
    node_id         NUMBER(10)          NOT NULL,
    node_type       VARCHAR2(10 CHAR)  NOT NULL,
    node_nm         VARCHAR2(50 CHAR)  NOT NULL,
    node_desc       VARCHAR2(100 CHAR),
    site_cd         VARCHAR2(10 CHAR),
    location_nm     VARCHAR2(50 CHAR),
    parent_node_id  NUMBER(10),
    sort_ord        NUMBER(10)          DEFAULT 0 NOT NULL,
    PRIMARY KEY (node_id),
    CONSTRAINT fk_net_node_parent FOREIGN KEY (parent_node_id) REFERENCES tb_net_node (node_id),
    CONSTRAINT ck_net_node_type   CHECK (node_type IN ('HUB', 'SWITCH'))
);

CREATE TABLE tb_server (
    server_id       NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    system_nm       VARCHAR2(100 CHAR) NOT NULL,
    fqdn            VARCHAR2(255 CHAR) NOT NULL,
    os_type         VARCHAR2(30 CHAR)  DEFAULT 'SOLARIS' NOT NULL,
    ip_addr         VARCHAR2(45 CHAR)  NOT NULL,
    switch_node_id  NUMBER(10)          NOT NULL,
    status_cd       VARCHAR2(10 CHAR)  NOT NULL,
    sync_status     VARCHAR2(50 CHAR),
    pair_server_id  NUMBER(19),
    sort_ord        NUMBER(10)          DEFAULT 0 NOT NULL,
    reg_dt          TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    upd_dt          TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PRIMARY KEY (server_id),
    CONSTRAINT uk_server_ip      UNIQUE (ip_addr),
    CONSTRAINT fk_server_switch  FOREIGN KEY (switch_node_id) REFERENCES tb_net_node (node_id),
    CONSTRAINT fk_server_pair    FOREIGN KEY (pair_server_id) REFERENCES tb_server (server_id),
    CONSTRAINT ck_server_status  CHECK (status_cd IN ('Active', 'Standby', 'Down'))
);

CREATE TABLE tb_server_metric (
    server_id       NUMBER(19)       NOT NULL,
    cpu_pct         DECIMAL(5,1),
    mem_pct         DECIMAL(5,1),
    disk_pct        DECIMAL(5,1),
    session_cnt     NUMBER(10),
    collect_dt      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PRIMARY KEY (server_id),
    CONSTRAINT fk_metric_server FOREIGN KEY (server_id) REFERENCES tb_server (server_id)
);

CREATE TABLE tb_server_process (
    proc_id         NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    server_id       NUMBER(19)       NOT NULL,
    proc_nm         VARCHAR2(100 CHAR) NOT NULL,
    exec_path       VARCHAR2(255 CHAR) NOT NULL,
    pid             NUMBER(10),
    cpu_pct         DECIMAL(5,1) DEFAULT 0 NOT NULL,
    mem_pct         DECIMAL(5,1) DEFAULT 0 NOT NULL,
    running_yn      CHAR(1)      DEFAULT 'N' NOT NULL,
    sort_ord        NUMBER(10)          DEFAULT 0 NOT NULL,
    reg_dt          TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    upd_dt          TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PRIMARY KEY (proc_id),
    CONSTRAINT fk_process_server FOREIGN KEY (server_id) REFERENCES tb_server (server_id),
    CONSTRAINT ck_process_running CHECK (running_yn IN ('Y', 'N'))
);

CREATE INDEX ix_server_process_server ON tb_server_process (server_id, sort_ord);

