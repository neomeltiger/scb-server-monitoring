package com.scb.monitoring.config.db;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.util.List;

import org.junit.jupiter.api.Test;

/** MySQL 보완 생성 (SchemaUpgrade) : schema-ansi.sql 의 IDENTITY / CLOB 을 MySQL 문법으로 */
class DbDialectMysqlTest {

    @Test
    void identityAndClobConverted() {
        String ansi = "DROP TABLE IF EXISTS t_x;\n"
                + "CREATE TABLE t_x (\n    x_id BIGINT GENERATED BY DEFAULT AS IDENTITY, body CLOB,\n    PRIMARY KEY (x_id)\n);\n";
        List<String> out = DbDialect.ddl(ansi, DbKind.MYSQL);
        assertEquals(1, out.size(), "DROP 은 뺌");
        String sql = out.get(0);
        assertTrue(sql.contains("x_id BIGINT AUTO_INCREMENT"), sql);
        assertTrue(sql.contains("body MEDIUMTEXT"), sql);
        assertFalse(sql.toUpperCase().contains("IDENTITY"), sql);
    }
}
